"""The content hub API, backing the client-first redesign at /content-generation.

Entirely separate from the six older routers. It reads the `cg_*` tables, which
services.content_generation_sync derives from the source tables. No route here
writes to anything the old app owns, and no old route reads anything here, so
the two stacks can run side by side indefinitely.

WHO OWNS THE CLIENT LIST. Command HQ does, and nothing here copies it.
`/clients` calls the HQ export live on every request and returns what it says,
exactly as the older forms' prefill dropdown does. `cg_clients` exists only so
runs and assets have something to hang off, so a client with no content has no
row here at all, which is true of most of the 361. That is why every count on
this API is allowed to be zero and why no route 404s for a client HQ knows and
we do not.

Every client-scoped route takes HQ's uuid, typed `uuid.UUID` so a malformed id
is a 422 from FastAPI rather than an InvalidTextRepresentation 500 from psycopg.

VOCABULARY. `content_type` is the tab (website, social, blog, logo, ads) and
`section` is the sub type inside it (pages, posts, reels, stories, reviews,
blogs, scratch, revamp, ads). v1 used `section` for the tab; nothing here does.

  GET  /clients                            the switcher, live from HQ
  GET  /clients/{client_id}/overview       tabs, counts and run history
  GET  /clients/{client_id}/assets         the items for one tab
  GET  /clients/{client_id}/draft          the last brief, for the form to open on
  POST /clients/{client_id}/runs           request a run; 202, generates behind it
  GET  /assets/{asset_id}                  one item with its version history
  POST /assets/{asset_id}/approve          sign-off, which only the hub records
  POST /assets/{asset_id}/restore          make an older version the active one
  POST /assets/{asset_id}/image            book artwork, only once copy is approved
  GET  /assets/{asset_id}/chat             one version's conversation
  POST /assets/{asset_id}/chat             append to it
  GET  /settings                           per-section item counts
  PUT  /settings/{section}                 set one, house or per client
  DEL  /settings/{section}                 drop a client override
  POST /sync                               re-derive content from the old tables

IMAGES ARE NEVER GENERATED BY A RUN. A run produces content assets only. Artwork
is booked afterwards through /assets/{id}/image, which refuses unless the copy it
would illustrate is approved. That is a server-side rule, not a hidden button:
copy nobody has read is exactly what you do not want a designer building from.
"""

