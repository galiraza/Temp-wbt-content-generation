@router.put("/settings/{section}", response_model=List[schemas.HubSectionDefaultOut])
def set_section_default(
    section: HubSection,
    payload: schemas.HubSectionDefaultIn,
    client_id: Optional[uuid.UUID] = Query(
        None, description="Omit to set the house default; pass one to override it."
    ),
    db: Session = Depends(get_db),
):
    """Sets one count. Returns the whole panel, not just the row that changed.

    The whole panel because a client override changes how its own row reads
    (`source` becomes `client`) and a house change moves every row that
    inherits it. Returning one row would leave the rest stale and force a
    refetch anyway.
    """
    try:
        section_settings.put(db, section.value, payload.item_count, client_id)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    return [
        schemas.HubSectionDefaultOut(**row)
        for row in section_settings.describe(db, client_id)
    ]


@router.delete("/settings/{section}", response_model=List[schemas.HubSectionDefaultOut])
def clear_section_default(
    section: HubSection,
    client_id: uuid.UUID = Query(
        ..., description="Required: only a client override can be cleared."
    ),
    db: Session = Depends(get_db),
):
    """Drops a client override so the section inherits the house default again.

    `client_id` is required rather than optional. Clearing a house default would
    leave the section on a constant in Python that the panel can neither show
    nor change, so the value would look stuck. There is nothing to fall back to
    below the house level.
    """
    section_settings.clear(db, section.value, client_id)
    return [
        schemas.HubSectionDefaultOut(**row)
        for row in section_settings.describe(db, client_id)
    ]


