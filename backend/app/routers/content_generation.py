@router.post("/sync", response_model=schemas.HubSyncOut)
def sync(db: Session = Depends(get_db)):
    """Re-derives content from the older tables. Idempotent, safe to call anytime.

    Content only. The client list is never copied, because HQ owns it.
    """
    return sync_all(db)


@router.get(
    "/clients/{client_id}/assets/by-slug/{slug}",
    response_model=schemas.HubAssetDetailOut,
)
def get_asset_by_slug(
    client_id: uuid.UUID,
    slug: str,
    db: Session = Depends(get_db),
):
    """One asset addressed the way a URL addresses it.

    No section parameter, because (client_id, slug) is unique by index. That is
    what lets /sg/logos/concept-1/image be a complete address: the logo routes
    carry no section, and requiring one here would have pushed a disambiguator
    into the query string where a shared link would lose it.

    Returned as the same detail shape as /assets/{asset_id}, so a page reached
    by slug and one reached by id render from identical data.
    """
    asset = (
        db.query(models.ContentAsset)
        .filter(
            models.ContentAsset.client_id == client_id,
            models.ContentAsset.slug == slug,
        )
        .first()
    )
    if asset is None:
        raise HTTPException(status_code=404, detail="Asset not found")
    return schemas.HubAssetDetailOut(
        asset=_one_asset_out(db, asset),
        active_version=asset.active_version,
        versions=[
            schemas.HubVersionOut(
                version=version.version,
                body=version.body,
                file_path=version.file_path,
                created_at=version.created_at,
                is_active=version.version == asset.active_version,
            )
            for version in sorted(asset.versions, key=lambda v: v.version)
        ],
    )


