@router.get("/clients", response_model=List[schemas.HubClientOut])
def list_clients(db: Session = Depends(get_db)):
    """Every client HQ has, with our asset count where we hold content.

    Live from the export on every call. Nothing is written and no client is
    created: the switcher is a view onto HQ's list, and the count is the only
    column this app owns. A count of zero is the normal case.
    """
    # Latest runs only, matching the tab badges and the grids. Counting every
    # run made the picker say "40 assets" for a client whose panel then showed
    # 20, which is the same discrepancy one level up: a superseded run is
    # history, not content the client currently has.
    #
    # One window function over every client rather than the per-client helper in
    # a loop, which would be 361 queries to render one list.
    ranked = (
        db.query(
            models.ContentRun.run_id,
            func.row_number()
            .over(
                partition_by=[
                    models.ContentRun.client_id,
                    models.ContentRun.content_type,
                    models.ContentRun.period,
                ],
                order_by=models.ContentRun.version.desc(),
            )
            .label("rank"),
        )
        .subquery()
    )
    latest_any = db.query(ranked.c.run_id).filter(ranked.c.rank == 1).subquery()

    counts = dict(
        db.query(models.ContentAsset.client_id, func.count(models.ContentAsset.asset_id))
        .filter(models.ContentAsset.run_id.in_(select(latest_any.c.run_id)))
        .group_by(models.ContentAsset.client_id)
        .all()
    )
    # last_run_at travels on this same response rather than on a second
    # "recent clients" endpoint. The picker shows Recent and All as two tabs
    # over one list, so a second route would mean a second call to HQ for 361
    # rows to answer a question this one already has the data for.
    last_runs = dict(
        db.query(models.ContentClient.client_id, models.ContentClient.last_run_at)
        .filter(models.ContentClient.last_run_at.isnot(None))
        .all()
    )

    out = []
    for row in hq_list_clients():
        client_id = (row.get("clientId") or "").strip()
        name = (row.get("name") or "").strip()
        if not client_id or not name:
            continue
        # The count is keyed on a real uuid, so an export row whose id is not
        # one still lists, just with nothing attached.
        try:
            key = uuid.UUID(client_id)
        except ValueError:
            key = None
        count = counts.get(key, 0) if key else 0
        out.append(
            schemas.HubClientOut(
                client_id=client_id,
                client_name=name,
                client_organization=row.get("organizationId"),
                asset_count=count,
                last_run_at=last_runs.get(key) if key else None,
                meta=_meta(count),
            )
        )
    return out


@router.get("/clients/{client_id}/overview", response_model=schemas.HubOverviewOut)
def client_overview(client_id: uuid.UUID, db: Session = Depends(get_db)):
    """The tabs, their counts and the run history, in one call.

    Three queries total, whatever the client holds: the counts, blog's periods
    and the run history with its approval tallies.

    A client we hold nothing for is a 200 with every count at zero, not a 404.
    HQ owns the client list, so "this client exists and has no content" is an
    ordinary answer and the only one most of the 361 have.
    """
    local = db.get(models.ContentClient, client_id)
    counts = _asset_counts(db, client_id)
    periods = _blog_periods(db, client_id)

    content_types = []
    for content_type, label in CONTENT_TYPE_LABELS:
        key = content_type.value
        flags = CONTENT_TYPE_FLAGS[key]

        if content_type is HubContentType.blog:
            sections = [
                schemas.HubSectionOut(
                    id=period,
                    label=_month_label(period),
                    count=sum(n for ct, _, p, n in counts if ct == key and p == period),
                )
                for period in periods
            ]
        else:
            sections = [
                schemas.HubSectionOut(
                    id=section,
                    label=SECTION_LABELS[section],
                    count=sum(n for ct, s, _, n in counts if ct == key and s == section),
                )
                for section in SECTIONS_BY_CONTENT_TYPE[key]
            ]

        content_types.append(
            schemas.HubContentTypeOut(
                id=content_type,
                label=label,
                count=sum(n for ct, _, _, n in counts if ct == key),
                unit=flags["unit"],
                single=flags.get("single", False),
                table=flags.get("table", False),
                monthly=flags.get("monthly", False),
                logo=flags.get("logo", False),
                sections=sections,
            )
        )

    runs = _run_history(db, client_id)

    total = sum(n for _, _, _, n in counts)
    name = local.client_name if local else ""
    organization = str(local.client_organization) if local and local.client_organization else None
    if not name:
        # Only reached for a client we hold no row for, which is why the export
        # is not consulted in the common case.
        for row in _hq_clients():
            if (row.get("clientId") or "").strip() == str(client_id):
                name = (row.get("name") or "").strip()
                organization = row.get("organizationId")
                break

    return schemas.HubOverviewOut(
        client=schemas.HubClientOut(
            client_id=str(client_id),
            client_name=name,
            client_organization=organization,
            asset_count=total,
            meta=_meta(total),
        ),
        content_types=content_types,
        runs=runs,
    )


def _run_history(db: Session, client_id: uuid.UUID) -> List[schemas.HubRunOut]:
    """The newest runs with their "N of M approved" label.

    The tallies come back in one grouped query over the runs already fetched,
    rather than two counts per run, which is forty extra queries at this limit.
    """
    runs = (
        db.query(models.ContentRun)
        .filter(models.ContentRun.client_id == client_id)
        .order_by(models.ContentRun.created_at.desc())
        .limit(_HISTORY_LIMIT)
        .all()
    )
    if not runs:
        return []

    tallies = {
        run_id: (total, approved)
        for run_id, total, approved in db.query(
            models.ContentAsset.run_id,
            func.count(models.ContentAsset.asset_id),
            func.count(case((models.ContentAsset.status == "approved", 1))),
        )
        .filter(models.ContentAsset.run_id.in_([r.run_id for r in runs]))
        .group_by(models.ContentAsset.run_id)
        .all()
    }

    out = []
    for run in runs:
        total, approved = tallies.get(run.run_id, (0, 0))
        item = schemas.HubRunOut.model_validate(run)
        item.asset_count = total
        item.approved_count = approved
        item.approved_label = f"{approved} of {total} approved"
        out.append(item)
    return out


@router.get("/clients/{client_id}/assets", response_model=List[schemas.HubAssetOut])
def list_assets(
    client_id: uuid.UUID,
    content_type: HubContentType = Query(..., description="The tab"),
    section: Optional[HubSection] = Query(None, description="The sub tab, except for blog"),
    period: Optional[str] = Query(None, description="'YYYY-MM', blog's sub tab"),
    version: Optional[int] = Query(
        None,
        ge=1,
        description="An older run to view. Omit for the newest, which is the default.",
    ),
    db: Session = Depends(get_db),
):
    """The items for one tab, each carrying the content of the version it shows.

    THE NEWEST RUN ONLY, unless `version` names an older one. Returning every
    run's assets was the original behaviour and it was wrong: re-running social
    for a client put v1 and v2 in one grid, forty cards with nothing to say
    which were the new ones, and the tab badge disagreed with the count on the
    page. The superseded runs are reachable from the run history, which is what
    the history is for.

    For blog the newest run is per month, because its sub tabs are the months.
    See _latest_run_ids.

    The content is joined in on active_version. Outer joined, not inner, because
    an asset whose version row is missing is a state worth seeing rather than
    silently dropping from the list.
    """
    shown = models.ContentAsset.active_version

    query = (
        db.query(
            models.ContentAsset,
            models.ContentRun.content_type,
            models.ContentAssetVersion.body,
            models.ContentAssetVersion.file_path,
        )
        .join(models.ContentRun, models.ContentAsset.run_id == models.ContentRun.run_id)
        .outerjoin(
            models.ContentAssetVersion,
            and_(
                models.ContentAssetVersion.asset_id == models.ContentAsset.asset_id,
                models.ContentAssetVersion.version == shown,
            ),
        )
        .filter(
            models.ContentAsset.client_id == client_id,
            models.ContentRun.content_type == content_type.value,
        )
    )

    if version is not None:
        query = query.filter(models.ContentRun.version == version)
    else:
        latest = _latest_run_ids(db, client_id)
        if not latest:
            return []
        query = query.filter(models.ContentRun.run_id.in_(latest))

    if section is not None:
        query = query.filter(models.ContentAsset.section == section.value)
    if period is not None:
        query = query.filter(models.ContentRun.period == period)

    rows = query.order_by(
        models.ContentRun.version.desc(),
        models.ContentAsset.position,
        models.ContentAsset.asset_id,
    ).all()

    return [
        _asset_out(asset, ct, body, file_path)
        for asset, ct, body, file_path in rows
    ]


