@router.get("/assets/{asset_id}", response_model=schemas.HubAssetDetailOut)
def get_asset(asset_id: uuid.UUID, db: Session = Depends(get_db)):
    """One item and every version of it, oldest first.

    `is_active` marks what ships, which is not always what the card is showing:
    previewing an older version is client side only and leaves nothing
    alone, so the panel needs both to label the history honestly.
    """
    asset = _get_asset(db, asset_id)
    return schemas.HubAssetDetailOut(
        asset=_one_asset_out(db, asset),
        active_version=asset.active_version,
        versions=[
            schemas.HubVersionOut(
                version=version.version,
                body=version.body,
                file_path=version.file_path,
                created_at=version.created_at,
                is_active=version.version == asset.active_version,
            )
            for version in asset.versions
        ],
    )


@router.post("/assets/{asset_id}/approve", response_model=schemas.HubAssetOut)
def approve_asset(
    asset_id: uuid.UUID,
    approved: bool = Query(True),
    db: Session = Depends(get_db),
):
    """Sign-off, the one piece of state the hub owns rather than copies.

    Never written back to a source table. The older tables record no approval
    for text at all, and adding one would change behaviour the existing routes
    depend on, so this is the record.

    Un-approving clears approved_at rather than keeping it, so the column can
    always be read as "when this was signed off" without checking status too.
    """
    asset = _get_asset(db, asset_id)
    asset.status = "approved" if approved else "review"
    asset.approved_at = datetime.now(timezone.utc) if approved else None
    db.commit()
    db.refresh(asset)
    return _one_asset_out(db, asset)


@router.post("/assets/{asset_id}/restore", response_model=schemas.HubAssetOut)
def restore_version(
    asset_id: uuid.UUID,
    version: int = Query(..., ge=1),
    db: Session = Depends(get_db),
):
    """Make an older version the one that ships.

    The only version state the database keeps, since previewing is client side.
    """
    asset = _get_asset(db, asset_id)
    _get_version(db, asset_id, version)
    asset.active_version = version
    db.commit()
    db.refresh(asset)
    return _one_asset_out(db, asset)




