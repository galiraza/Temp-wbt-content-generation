@router.get("/assets/{asset_id}/chat", response_model=List[schemas.HubChatMessageOut])
def list_chat(
    asset_id: uuid.UUID,
    version: Optional[int] = Query(None, ge=1, description="Defaults to the displayed version"),
    db: Session = Depends(get_db),
):
    """One version's conversation, oldest first.

    The version defaults to the one the card is showing, because that is the
    text the panel has open and asking for the thread of anything else would be
    a deliberate act.
    """
    asset = _get_asset(db, asset_id)
    version = version if version is not None else asset.active_version
    _get_version(db, asset_id, version)

    return (
        db.query(models.ContentAssetChat)
        .filter(
            models.ContentAssetChat.asset_id == asset_id,
            models.ContentAssetChat.version == version,
        )
        .order_by(
            models.ContentAssetChat.created_at, models.ContentAssetChat.message_id
        )
        .all()
    )


@router.post(
    "/assets/{asset_id}/chat",
    response_model=schemas.HubChatMessageOut,
    status_code=201,
)
def add_chat_message(
    asset_id: uuid.UUID,
    payload: schemas.HubChatMessageCreate,
    version: Optional[int] = Query(None, ge=1, description="Defaults to the displayed version"),
    db: Session = Depends(get_db),
):
    """Append a message to one version's thread.

    The version is checked before the insert. cg_asset_chats has a composite
    foreign key to (asset_id, version), so skipping the check turns a typo into
    an IntegrityError 500 that names a constraint instead of the parameter.
    """
    asset = _get_asset(db, asset_id)
    version = version if version is not None else asset.active_version
    _get_version(db, asset_id, version)

    message = models.ContentAssetChat(
        asset_id=asset_id,
        version=version,
        body=payload.body,
    )
    db.add(message)
    db.commit()
    db.refresh(message)
    return message


