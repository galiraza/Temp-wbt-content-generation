#: Keys never handed back to a form.
#:
#: `prepared` and the intake products are derived, not typed. The rest is
#: bookkeeping from the sync: it records where a row came from in the v1 tables
#: and means nothing to someone filling in a form.
_DRAFT_HIDDEN = {
    "prepared",
    "sitemap_data",
    "meeting_insights",
    "resolved_industries",
    "status",
    "error_message",
    "note",
    "source_id",
    "source_table",
}


@router.get("/clients/{client_id}/draft", response_model=schemas.HubDraftOut)
def get_draft(
    client_id: uuid.UUID,
    content_type: HubContentType = Query(...),
    db: Session = Depends(get_db),
):
    """The brief the most recent run of this type used, for the form to open on.

    Returns an empty `source` rather than a 404 when the client has never had a
    run of this type. An empty form is the correct answer to "what did we use
    last time" when the answer is "nothing", and a 404 would make the form
    handle an error for the normal first-time case.

    Nothing here comes from the Command HQ export, which was asked for
    explicitly: the picker says who the run is for, the form says what to
    generate, and prefilling the second from the first put stale answers in
    front of someone who was there to type fresh ones.
    """
    run = (
        db.query(models.ContentRun)
        .filter(
            models.ContentRun.client_id == client_id,
            models.ContentRun.content_type == content_type.value,
        )
        .order_by(models.ContentRun.version.desc())
        .first()
    )
    if run is None:
        return schemas.HubDraftOut(content_type=content_type, source={})

    return schemas.HubDraftOut(
        content_type=content_type,
        source={
            key: value
            for key, value in (run.source or {}).items()
            if key not in _DRAFT_HIDDEN
        },
        run_id=run.run_id,
        version=run.version,
        created_at=run.created_at,
    )


@router.post(
    "/clients/{client_id}/runs", response_model=schemas.HubRunOut, status_code=202
)
def create_run(
    client_id: uuid.UUID,
    payload: schemas.HubRunCreate,
    background: BackgroundTasks,
    db: Session = Depends(get_db),
):
    """Books the run in, then generates behind it. Returns 202 with the run.

    202 rather than 201: the run exists, and the work it describes has not
    happened yet. A website run is up to seventeen agent calls, so doing it
    inside the request would hold the connection open for minutes and lose
    everything to the first timeout.

    The background task opens its own Session. Sharing this request Session
    would mean writing to it after the response closed it, which is the failure
    that produces assets vanishing on refresh.
    """
    try:
        run = content_run.create_run(
            db,
            client_id=client_id,
            content_type=payload.content_type.value,
            source=payload.source,
            period=payload.period,
            requested_by=payload.requested_by,
        )
    except content_run.RunError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc

    background.add_task(_execute_run, run.run_id)
    return schemas.HubRunOut(
        run_id=run.run_id,
        content_type=run.content_type,
        version=run.version,
        status=run.status,
        period=run.period,
        summary=run.summary,
        requested_by=run.requested_by,
        client_name=run.client_name,
        asset_count=0,
        approved_count=0,
        approved_label="",
        created_at=run.created_at,
    )


def _execute_run(run_id: uuid.UUID) -> None:
    """Runs one run to completion on its own Session.

    Swallows everything. This is a background task with nobody to raise to, and
    `execute` already settles the run status and summary, so an exception
    escaping here would only lose the log line. The rescue below exists for the
    case where `execute` itself blew up before it could settle anything, which
    would otherwise leave a row stuck on `generating` for ever.
    """
    db = SessionLocal()
    try:
        run = db.get(models.ContentRun, run_id)
        if run is None:
            logger.warning("content_run_vanished run_id=%s", run_id)
            return
        content_run.execute(db, run)
    except Exception:
        logger.exception("content_run_crashed run_id=%s", run_id)
        try:
            db.rollback()
            run = db.get(models.ContentRun, run_id)
            if run is not None and run.status in ("pending", "generating"):
                run.status = "failed"
                run.summary = "The run stopped unexpectedly. The log has the reason."
                db.commit()
        except Exception:
            logger.exception("content_run_status_rescue_failed run_id=%s", run_id)
    finally:
        db.close()


@router.post("/assets/{asset_id}/image", response_model=schemas.HubAssetOut)
def request_asset_image(
    asset_id: uuid.UUID,
    asset_type: str = Query("image", pattern="^(image|video)$"),
    db: Session = Depends(get_db),
):
    """Books the image or video that goes with an APPROVED content asset.

    The gate, enforced here and in the service. A run never produces artwork:
    copy is written first, a person reads it and approves it, and only then is
    there something worth illustrating. Refusing in the API as well as hiding
    the button matters because the button is not the only caller.

    Returns the booked asset with no version yet, so queued work is visible
    while it waits rather than appearing only when it is finished.
    """
    try:
        asset = content_run.request_image(db, asset_id, asset_type)
    except content_run.RunError as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    return _one_asset_out(db, asset)
