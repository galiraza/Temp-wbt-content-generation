def request_image(
    db: Session, asset_id: uuid.UUID, asset_type: str = "image"
) -> ContentAsset:
    """Creates the image asset that goes with an approved content asset.

    The gate. Refuses unless the content asset is `approved`, so artwork is
    only ever built from copy a person has read and signed off. Enforced here
    rather than by hiding the button, because the button is not the only caller.

    Returns the image asset row with no version yet: this books the work in and
    makes it visible. The generator fills version 1 in afterwards.
    """
    if asset_type not in ("image", "video"):
        raise RunError(f"{asset_type!r} is not something to request. Use image or video.")

    content = db.get(ContentAsset, asset_id)
    if content is None:
        raise RunError("That asset does not exist.")
    if content.type != "content":
        raise RunError(
            "Images are requested against a content asset, not against another "
            "image."
        )
    if content.status != "approved":
        raise RunError(
            "This content is not approved yet. Approve the copy first, then the "
            "image can be made from it."
        )

    existing = db.execute(
        select(ContentAsset).where(
            ContentAsset.run_id == content.run_id,
            ContentAsset.section == content.section,
            ContentAsset.position == content.position,
            ContentAsset.type == asset_type,
        )
    ).scalar_one_or_none()
    if existing is not None:
        return existing

    image = ContentAsset(
        run_id=content.run_id,
        client_id=content.client_id,
        section=content.section,
        type=asset_type,
        position=content.position,
        title=content.title,
        status="generating",
        active_version=1,
        # No slug. The content asset owns the client-unique slug for this
        # position, and the URL contract already carries the type as its own
        # segment: /sg/logos/concept-1/content and /sg/logos/concept-1/image
        # are the same slug, different type.
        slug=None,
    )
    db.add(image)
    db.commit()
    db.refresh(image)
    logger.info(
        "content_image_requested asset_id=%s from=%s type=%s",
        image.asset_id,
        asset_id,
        asset_type,
    )
    return image


def generate(
    db: Session,
    client_id: uuid.UUID,
    content_type: str,
    source: Dict[str, Any],
    period: Optional[str] = None,
    requested_by: Optional[str] = None,
) -> ContentRun:
    """create_run then execute, for callers that want the whole thing.

    Synchronous, which is fine for a background task and wrong for a request
    handler: a website run is seventeen agent calls. The router creates the run,
    returns it, and calls this from a background task.
    """
    run = create_run(db, client_id, content_type, source, period, requested_by)
    return execute(db, run)
